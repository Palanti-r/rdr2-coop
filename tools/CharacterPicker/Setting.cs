using System;
using System.Collections.Generic;
using System.IO;
using System.Text.RegularExpressions;

sealed class Setting
{
    static readonly HashSet<string> ConnectionKeys = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
    {
        "Name", "RunServer", "Server", "Port", "Password", "PreferHost", "HostPort", "HostPassword",
        "RoomName", "Public", "UPnP", "GuestCharacter",
    };

    public readonly string Section, Key, Default, Description;
    public string Label => Regex.Replace(Key, @"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", " ");

    Setting(string section, string key, string fallback, string description)
    {
        Section = section;
        Key = key;
        Default = fallback;
        Description = description;
    }

    public static IEnumerable<Setting> FromTemplate(string text)
    {
        using (var reader = new StringReader(text))
        {
            string section = "", line;
            var comments = new List<string>();
            while ((line = reader.ReadLine()) != null)
            {
                line = line.Trim();
                if (line.StartsWith("[") && line.EndsWith("]")) section = line.Substring(1, line.Length - 2);
                if (line.StartsWith("; "))
                {
                    comments.Add(line.Substring(2));
                    continue;
                }
                int equals = line.IndexOf('=');
                if (section.Length > 0 && equals > 0 && !line.StartsWith(";"))
                {
                    string key = line.Substring(0, equals).Trim();
                    bool diagnostics = section == "Testing" && key == "DebugMode";
                    if (!diagnostics && (section != "Coop" || !ConnectionKeys.Contains(key)))
                    {
                        string description = string.Join(" ", comments);
                        if (description.StartsWith(key + ":", StringComparison.OrdinalIgnoreCase))
                            description = description.Substring(key.Length + 1).TrimStart();
                        yield return new Setting(section, key, line.Substring(equals + 1).Trim(), description);
                    }
                }
                comments.Clear();
            }
        }
    }

    // Settings read by the mod that aren't listed in the default INI.
    public static IEnumerable<Setting> Additional()
    {
        foreach (string key in new[] { "Poker", "Blackjack", "Dominoes", "Dice", "Race", "Duel", "Shooting", "Hunting" })
            yield return new Setting("Games", key, "Yes", "Enable this co-op game or contest.");
        yield return new Setting("Games", "HighCard", "No", "Enable the sample high-card game.");
        yield return new Setting("Net", "DriveMode", "", "Experimental movement mode for mirrored peds. Blank uses the mod's default.");

        foreach (string key in new[]
        {
            "SpawnWagon", "SpawnTrain", "SetClock", "PokerForceFold", "PokerDeckTest", "PokerSendAway",
            "CutsceneTest", "SoftsaveProbe", "SoftsaveDump", "SoftsaveInject", "TravelTo",
        })
            yield return new Setting("Keys", key, "", "Developer shortcut. Leave blank to disable it.");

        yield return new Setting("Testing", "LogsInstall", "", "The ID generated by the co-op logging system.");
        yield return new Setting("Testing", "TraceJoins", "No", "Log extra detail when players join, leave, or enter cutscenes.");
        yield return new Setting("Testing", "RecordMissions", "Yes", "Include mission recordings when log sharing is enabled.");
        yield return new Setting("Testing", "KeepRecordings", "No", "Keep local copies of mission recordings.");
        yield return new Setting("Testing", "RecordAllScripts", "No", "Record all scripts during mission recording.");
        yield return new Setting("Testing", "PokerTrace", "No", "Record the game's poker activity in the local log.");
        yield return new Setting("Testing", "ClockHour", "13", "Hour used by the Set Clock shortcut (0 to 23).");
        yield return new Setting("Testing", "TravelTo", "-283,790,118", "X, Y, Z coordinates used by the Travel To shortcut.");
        yield return new Setting("Testing", "TravelName", "Valentine", "Label for the test travel destination.");
        yield return new Setting("Testing", "RideDoubleSteer", "rider", "How a partner's horse steers when you ride behind them. Use rider, horse, or none.");
        yield return new Setting("Testing", "RideDoubleGroup", "No", "Use the experimental group mode for riding double.");
        yield return new Setting("Testing", "BubbleVolumes", "No", "Use volume-based spawn blocking when Bubbles is enabled.");
        yield return new Setting("Testing", "CutsceneAsStory", "No", "Share test cutscenes with the mission party when hosting.");
        yield return new Setting("Testing", "CutsceneBindPlayer", "Yes", "Bind the local character in a test cutscene.");
        yield return new Setting("Testing", "CutsceneLabel", "", "Test cutscene label. Blank uses the mod's default.");
        yield return new Setting("Testing", "CutscenePlayback", "", "Test cutscene playback list. Blank uses the mod's default.");
        yield return new Setting("Testing", "CutsceneNames", "ARTHUR,player_zero", "Comma-separated player actor names for a test cutscene.");
        yield return new Setting("Testing", "CutsceneMission", "mudtown3", "Mission whose actor map the test cutscene uses.");
        yield return new Setting("Testing", "CutsceneSpawn", "", "Comma-separated actor:model pairs for a test cutscene.");
    }

    public string[] Choices()
    {
        if (Key == "SendLogs") return new[] { "", "Yes", "No" };
        if (Default == "Yes" || Default == "No") return new[] { "Yes", "No" };
        if (Default == "True" || Default == "False") return new[] { "True", "False" };
        if (Key == "VehicleMode") return new[] { "glide", "drive" };
        if (Key == "RideDoubleSteer") return new[] { "rider", "horse", "none" };
        return Array.Empty<string>();
    }
}
